import json, re
R=json.load(open('ford-catalog-raw.json'))
G={'Stil Şi Personalizare':'Stil și personalizare','Experienţa la Volan':'Experiența la volan','Confort':'Confort','Pachete Opţionale':'Pachete opționale','Utilitate':'Utilitate','Siguranţă':'Siguranță','Jante':'Jante și roți','Performanţă':'Performanță','Opționale':'Opționale'}
CAT={'puma':'WSEAM-CF7-2024-PumaROU202700','kuga':'WSEAM-CTD-2024-KugaROU202700','capri':'WSEAM-CFU-2024-CapriROU202725','explorer':'WSEAM-CFU-2024-ExplorerEVROU202725','transit-custom':'WSEAM-TTU-2023-TransitCustomROU202700','ranger':'WSEAM-TRB-2026-RangerSouthAfricaROU202700'}
def meta(name,mid):
    n=name
    if re.search(r'Electric|kWh|E-Transit',n): f='ev'
    elif 'PHEV' in n: f='phev'
    elif 'FHEV' in n: f='hev'
    elif mid=='puma': f='mhev'
    elif re.search(r'Diesel|EcoBlue|V6',n): f='diesel'
    else: f='ice'
    gb='manual' if re.search(r'\bM6\b|Manual',n) else 'auto'
    dr='AWD' if 'AWD' in n else '4WD' if '4WD' in n else 'RWD' if 'RWD' in n else 'FWD'
    kwh=(re.search(r'(\d+) ?kWh',n) or [None,None])[1]
    return f,gb,dr,kwh
CFG={}; VERS={}
for mid,M in R.items():
    E=M['E']; O=M['O']
    # known breakdown per engine index
    known={}
    for s in M['s']:
        for e in s['e']:
            if e[1] and e[3]: known.setdefault(e[0],(e[2] or 0,e[3] or 0))
    allk=list(known.values())
    series=[]
    base_col=M['s'][0]['col']; base_int=M['s'][0]['int']
    for s in M['s']:
        eng=[]; seen=set()
        for e in s['e']:
            ei=e[0]
            if ei in seen: continue
            seen.add(ei)
            lst,rab,adv,promo,bar=e[1:6]; est=len(e)>6
            if not lst:
                if not (promo or bar): continue
                promo=promo or bar
                rab,adv=known.get(ei, allk[0] if allk else (0,0))
                if mid in('ranger',): rab=0
                lst=promo+rab+adv; est=True
            nm,cp=E[ei][1],E[ei][2]
            f,gb,dr,kwh=meta(nm,mid)
            if not cp:
                m=re.search(r'(\d{2,3}) ?CP',nm); cp=m.group(1) if m else ''
            eng.append(dict(c=E[ei][0],n=nm,cp=int(cp) if cp else None,fuel=f,gb=gb,dr=dr,kwh=kwh,list=lst,rabla=rab or 0,adv=adv or 0,promo=promo or lst,est=est))
        kp={e['promo'] for e in eng if not e['est']}
        eng=[e for e in eng if not (e['est'] and e['promo'] in kp)] or eng
        eng.sort(key=lambda x:x['list'])
        col=s['col'] or base_col
        cols=[]; chips=set()
        for c in col:
            if c[2] in chips: continue
            chips.add(c[2]); cols.append(dict(n=c[0],p=c[1],chip=c[2],img=['https://www.gpas-cache.ford.com/guid/%s.jpg'%g for g in c[3]]))
        ints=[]; seen=set()
        for i in (s['int'] or base_int):
            if i[0] in seen: continue
            seen.add(i[0]); ints.append(dict(n=i[0],p=i[1]))
        opts=[]; seen=set()
        for oi,p in s['opt']:
            g,n=O[oi]
            if (g,n) in seen or p==0: continue
            seen.add((g,n)); n=n[0].upper()+n[1:]
            opts.append(dict(g=G.get(g,g),n=n.rstrip(':'),p=p))
        series.append(dict(c=s['c'],n=s['n'],hi=s['hi'],e=eng,col=cols,int=ints,opt=opts))
    C=dict(cat=CAT[mid],series=series)
    if mid=='transit-custom':
        C['bodies']=[dict(n={'ro':'Furgon (Van) L1H1','en':'Van L1H1'},d=0),dict(n={'ro':'Furgon (Van) L2H1','en':'Van L2H1'},d=0,note={'ro':'Diferența de preț se confirmă în ofertă.','en':'Price difference confirmed in the quote.'}),dict(n={'ro':'Double Cab-in-Van (DCIV)','en':'Double Cab-in-Van (DCIV)'},d=0,note={'ro':'Diferența de preț se confirmă în ofertă.','en':'Price difference confirmed in the quote.'}),dict(n={'ro':'Kombi M1 (persoane)','en':'Kombi M1 (passenger)'},d=0,note={'ro':'Diferența de preț se confirmă în ofertă.','en':'Price difference confirmed in the quote.'})]
    CFG[mid]=C
    # versions for prices pages: one per series x engine
    vs=[]
    for s in series:
        for e in s['e']:
            vs.append(dict(trim=s['n'],engine=e['n'],list=e['list'],promo=e['promo'] if e['promo']<e['list'] else None,rabla=e['rabla'],adv=e['adv'],cp=e['cp'],kwh=e['kwh'],gb=e['gb'],dr=e['dr'],fuel=e['fuel'],f=s['hi'][:5],sc=s['c'],ec=e['c'],est=e['est']))
    VERS[mid]=vs
out='window.SP = window.SP || {};\n/* generated by gen.py from ford.ro configurator data (Ford România, Oct 2026) */\nSP.CFG = '+json.dumps(CFG,ensure_ascii=False,separators=(',',':'))+';\nSP.CFG_VERSIONS = '+json.dumps(VERS,ensure_ascii=False,separators=(',',':'))+';\n'
open('assets/js/config-data.js','w').write(out)
for k,v in VERS.items(): print(k,len(v),min(x['list'] for x in v),sum(x['est'] for x in v))
print(len(out))
